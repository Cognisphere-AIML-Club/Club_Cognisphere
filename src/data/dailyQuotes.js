// Fixed epoch base: Nov 16, 2026 (index 0)
const BASE_DATE_UTC = Date.UTC(2026, 10, 16);

/**
 * Returns the deterministic quote index for any given calendar date.
 * Every calendar day advances the index by 1, wrapping around the collection.
 */
export function getDailyQuoteIndex(date = new Date()) {
  const targetDateUTC = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  const diffDays = Math.floor((targetDateUTC - BASE_DATE_UTC) / (1000 * 60 * 60 * 24));
  const len = DAILY_QUOTES.length;
  return ((diffDays % len) + len) % len;
}

/**
 * Returns today's quote of the day.
 */
export function getDailyQuote(date = new Date()) {
  const index = getDailyQuoteIndex(date);
  return DAILY_QUOTES[index];
}

/**
 * Returns a random quote index different from the current index.
 */
export function getRandomQuoteIndex(currentIndex = -1) {
  if (DAILY_QUOTES.length <= 1) return 0;
  let nextIndex;
  do {
    nextIndex = Math.floor(Math.random() * DAILY_QUOTES.length);
  } while (nextIndex === currentIndex);
  return nextIndex;
}

